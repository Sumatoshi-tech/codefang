#[test]
fn unwired_list_matches_get_language() {
    for (stem, _) in cf_uast_mappings::ALL {
        let wired = cf_uast::languages::get_language(stem).is_some();
        let listed = UNWIRED.contains(stem);
        assert!(
            wired != listed,
            "{stem}: wired={wired} but unwired-listed={listed} — update UNWIRED"
        );
    }
    // No stale entries for languages that do not exist at all.
    let stems: BTreeSet<&str> = cf_uast_mappings::ALL.iter().map(|(s, _)| *s).collect();
    for u in UNWIRED {
        assert!(
            stems.contains(u),
            "UNWIRED entry {u} is not a known language"
        );
    }
}

#[test]
fn every_pattern_compiles_on_wired_grammars() {
    let allow: BTreeSet<(&str, &str)> = DEAD_RULE_ALLOW_LIST.iter().copied().collect();
    let mut checked = 0usize;
    let mut failures: Vec<String> = Vec::new();
    for (stem, mapping) in cf_uast_mappings::ALL {
        let Some(lang) = cf_uast::languages::get_language(stem) else {
            continue;
        };
        for rule in mapping.rules {
            checked += 1;
            match tree_sitter::Query::new(&lang, rule.pattern) {
                Ok(_) => {
                    assert!(
                        !allow.contains(&(*stem, rule.name)),
                        "{stem}/{}: allow-listed rule now compiles — remove the entry",
                        rule.name
                    );
                }
                Err(e) if allow.contains(&(*stem, rule.name)) => {
                    let _ = e; // acknowledged dead rule.
                }
                Err(e) => {
                    failures.push(format!(
                        "{stem}/{}: pattern {:?}: {e}",
                        rule.name, rule.pattern
                    ));
                }
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} non-allow-listed pattern failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
    assert!(
        checked > 1_000,
        "only {checked} rules checked — wiring regressed?"
    );
}
