#[test]
fn languages_filter_selects_per_language_totals_identically_across_formats() {
    let dir = fixture();
    let path = dir.path().to_str().unwrap();

    // `--languages Go` (basename globs `*.go`): the 4 Go files, in every format.
    let (json, text, yaml) = complexity_totals(path, &permissive_with_globs(&["*.go"]));
    assert_eq!((json, text, yaml), (4, 4, 4), "Go-only selection diverged");

    // `--languages Python`: only helper.py survives the walk.
    let (json, text, yaml) = complexity_totals(path, &permissive_with_globs(&["*.py"]));
    assert_eq!(
        (json, text, yaml),
        (1, 1, 1),
        "Python-only selection diverged"
    );

    // No globs (`--languages all` / flag absent): no restriction.
    let (json, text, yaml) = complexity_totals(path, &permissive());
    assert_eq!((json, text, yaml), (5, 5, 5), "unrestricted walk diverged");
}

#[test]
fn run_rejects_unknown_language_token_with_exit_1() {
    let dir = fixture();
    // The CLI error contract: an unresolvable `--languages` token aborts the
    // run (`Error: static --languages: unknown language: "notalang"`, exit 1)
    // instead of silently analyzing everything.
    let code = cf_commands::run([
        "codefang",
        "run",
        "--analyzers",
        "static/complexity",
        "--format",
        "json",
        "--languages",
        "NotALang",
        dir.path().to_str().unwrap(),
    ]);
    assert_eq!(code, 1, "unknown --languages token must exit 1");
}

#[test]
fn multi_analyzer_merge_paths_observe_the_walk_filter() {
    let dir = fixture();
    let path = dir.path().to_str().unwrap();

    // The merged multi-analyzer renders walk once per analyzer with the SAME
    // shared filter; if any merge path dropped it, the permissive and default
    // outputs would collapse to identical bytes.
    let json_perm = static_multi_json(&["static/*"], path, &permissive(), false).expect("json");
    let json_def =
        static_multi_json(&["static/*"], path, &StaticFilter::default(), false).expect("json");
    assert_ne!(
        json_perm, json_def,
        "static_multi_json ignored the walk filter"
    );

    let text_perm = static_multi_text(&["static/*"], path, &permissive()).expect("text");
    let text_def = static_multi_text(&["static/*"], path, &StaticFilter::default()).expect("text");
    assert_ne!(
        text_perm, text_def,
        "static_multi_text ignored the walk filter"
    );

    // The language restriction must reach the merge walks too.
    let json_py = static_multi_json(
        &["static/*"],
        path,
        &permissive_with_globs(&["*.py"]),
        false,
    )
    .expect("json");
    assert_ne!(
        json_perm, json_py,
        "static_multi_json ignored the language globs"
    );
}

