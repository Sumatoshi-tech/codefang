/// The single-run json report value of `id` through its crate-owned builder
/// (the exact value `--format json` encodes).
fn single_json_value(id: &str, path: &str, filter: &StaticFilter, per_file: bool) -> GoValue {
    let value = match id {
        "static/clones" => static_clones::clones_report_value_flags(path, filter, per_file),
        "static/complexity" => {
            static_complexity::complexity_report_value_flags(path, filter, per_file)
        }
        "static/comments" => static_comments::comments_report_value_flags(path, filter, per_file),
        "static/halstead" => static_halstead::halstead_report_value_flags(path, filter, per_file),
        "static/cohesion" => static_cohesion::cohesion_report_value_flags(path, filter, per_file),
        "static/imports" => static_imports::imports_report_value_flags(path, filter, per_file),
        "static/composition" => static_json::composition_report_value_flags(path, filter, per_file),
        other => panic!("unknown static analyzer {other}"),
    };
    value.unwrap_or_else(|| panic!("{id}: no report"))
}

/// The single-run text render of `id` (the summary value the text handler
/// feeds the renderer).
fn single_text(id: &str, path: &str, filter: &StaticFilter) -> String {
    let value = match id {
        "static/clones" => static_clones::clones_report_value_flags(path, filter, false),
        "static/complexity" => static_complexity::complexity_report_value_summary(path, filter),
        "static/comments" => static_comments::comments_report_value_summary(path, filter),
        "static/halstead" => static_halstead::halstead_report_value_summary(path, filter),
        "static/cohesion" => static_cohesion::cohesion_report_value_summary(path, filter),
        "static/imports" => static_imports::imports_report_value_flags(path, filter, false),
        "static/composition" => static_json::composition_report_value_opts(path, filter),
        other => panic!("unknown static analyzer {other}"),
    };
    let text = render_text_report(&value.unwrap_or_else(|| panic!("{id}: no report")));
    strip_ansi(std::str::from_utf8(&text).expect("utf-8 text"))
}

/// Parses a report GoValue (or merged json bytes) into a serde tree.
fn parsed(bytes: &[u8]) -> Value {
    serde_json::from_slice(bytes).expect("report json parses")
}

/// The first (only) section of a single-run report.
fn single_section(id: &str, path: &str, filter: &StaticFilter, per_file: bool) -> Value {
    let value = single_json_value(id, path, filter, per_file);
    parsed(&cf_gojson::marshal(&value))["sections"][0].clone()
}

/// The merged `static/*` json carries each analyzer's section EXACTLY as the
/// single run builds it — with and without `--per-file`, under the default
/// and the permissive filter.
#[test]
fn merged_json_sections_equal_the_single_runs_for_every_analyzer() {
    let dir = fixture();
    let path = dir.path().to_str().unwrap();
    for filter in [StaticFilter::default(), permissive()] {
        for per_file in [false, true] {
            let merged = parsed(
                &static_multi_json(&["static/*"], path, &filter, per_file).expect("merged json"),
            );
            let sections = merged["sections"].as_array().expect("sections array");
            assert_eq!(sections.len(), STATIC_ANALYZERS.len());
            for (section, id) in sections.iter().zip(STATIC_ANALYZERS) {
                assert_eq!(
                    section,
                    &single_section(id, path, &filter, per_file),
                    "{id} (per_file={per_file}): merged section differs from the single run"
                );
            }
        }
    }
}

/// The merged `static/*` bin output is the concatenation of the single-run
/// CFB1 envelopes in registry order.
#[test]
fn merged_bin_is_the_concatenation_of_the_single_runs() {
    let dir = fixture();
    let path = dir.path().to_str().unwrap();
    for filter in [StaticFilter::default(), permissive()] {
        let merged = static_multi_bin(&["static/*"], path, &filter).expect("merged bin");
        let mut expected = Vec::new();
        for id in STATIC_ANALYZERS {
            expected.extend(static_single_bin(id, path, &filter).expect("single bin"));
        }
        assert!(
            merged == expected,
            "merged bin differs from the single runs"
        );
    }
}

/// The merged `static/*` text render contains each analyzer's single text
/// body verbatim (the executive summary is the only addition).
#[test]
fn merged_text_contains_every_single_text_body() {
    let dir = fixture();
    let path = dir.path().to_str().unwrap();
    let filter = StaticFilter::default();
    let merged = static_multi_text(&["static/*"], path, &filter).expect("merged text");
    let merged = strip_ansi(std::str::from_utf8(&merged).expect("utf-8"));
    for id in STATIC_ANALYZERS {
        let single = single_text(id, path, &filter);
        let body = single.trim();
        assert!(
            merged.contains(body),
            "{id}: single text body missing from the merged render:\n--- single ---\n{body}\n--- merged ---\n{merged}"
        );
    }
}

/// The headline total of every analyzer agrees across json, text and yaml
/// (the formats that print it), under both filters: ONE walk feeds them all.
#[test]
fn headline_totals_agree_across_formats_for_every_analyzer() {
    let dir = fixture();
    let path = dir.path().to_str().unwrap();
    // (id, json/text metric label, yaml key — `None` when the yaml value
    // carries no comparable total).
    const TOTALS: [(&str, &str, Option<&str>); 7] = [
        ("static/clones", "Total Functions", Some("total_functions:")),
        (
            "static/complexity",
            "Total Functions",
            Some("total_functions:"),
        ),
        (
            "static/comments",
            "Total Functions",
            Some("total_functions:"),
        ),
        (
            "static/halstead",
            "Total Functions",
            Some("total_functions:"),
        ),
        (
            "static/cohesion",
            "Total Functions",
            Some("total_functions:"),
        ),
        ("static/imports", "Total Files", None),
        ("static/composition", "Total Files", Some("total_files:")),
    ];
    for filter in [StaticFilter::default(), permissive()] {
        for (id, label, yaml_key) in TOTALS {
            let json = cf_gojson::marshal(&single_json_value(id, path, &filter, false));
            let json_total =
                digits_after(std::str::from_utf8(&json).unwrap(), &format!("\"{label}\""));
            let text_total = digits_after(&single_text(id, path, &filter), label);
            assert_eq!(
                json_total, text_total,
                "{id}: json vs text {label} disagree"
            );
            if let Some(key) = yaml_key {
                let yaml = single_yaml(id, path, &filter);
                let yaml_total = digits_after(std::str::from_utf8(&yaml).unwrap(), key);
                assert_eq!(
                    json_total, yaml_total,
                    "{id}: json vs yaml {label} disagree"
                );
            }
        }
    }
}

/// The single-run yaml bytes of `id`.
fn single_yaml(id: &str, path: &str, filter: &StaticFilter) -> Vec<u8> {
    let bytes = match id {
        "static/clones" => static_clones::clones_report_yaml(path, filter),
        "static/complexity" => static_complexity_yaml::complexity_report_yaml(path, filter),
        "static/comments" => static_comments::comments_report_yaml(path, filter),
        "static/halstead" => static_halstead::halstead_yaml_report(path, filter),
        "static/cohesion" => static_cohesion::cohesion_report_yaml(path, filter),
        "static/composition" => static_json::composition_yaml_opts(path, filter),
        other => panic!("no yaml total for {other}"),
    };
    bytes.unwrap_or_else(|| panic!("{id}: no yaml"))
}
