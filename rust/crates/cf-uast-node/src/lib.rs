//! `cf-uast-node` — the canonical UAST (Universal Abstract Syntax Tree) node
//! representation and the operations that travel with it.
//!
//! This is a faithful Rust port of the Go package `pkg/uast/pkg/node`. It is the
//! keystone data type of codefang: it is imported by `uast`, `framework`,
//! `analyze`, and nearly every analyzer. The most byte-identity-critical export
//! is [`Node::to_map`], whose output is serialized into machine reports — its
//! keys (`children`, `id`, `pos`, `props`, `roles`, `token`, `type`) must emit in
//! raw-UTF-8 byte order to match Go's `encoding/json` map encoding. To guarantee
//! that, [`Node::to_map`] returns a [`GoValue`] built from a map-origin [`GoMap`]
//! (sort-on-encode), never `serde_json`. See DESIGN.md §2.2.
//!
//! # Relationship to `cf-gojson`
//!
//! The design routes all report serialization through the shared `cf-gojson`
//! crate. [`Node::to_map`] builds its output directly from
//! [`cf_gojson::GoValue`] / [`cf_gojson::GoMap`]; those two types are
//! re-exported here so callers can construct and serialize `to_map` output
//! without naming the encoder crate themselves.
//!
//! # Differences from the Go original
//!
//! - Go uses a `sync.Pool` for `Node`/`Positions` reuse. Rust's ownership model
//!   makes that pattern both unnecessary and unsafe across threads, so the global
//!   pool collapses into ordinary [`Node::new`] construction; the per-worker
//!   free-list [`Allocator`] is ported as a real object pool (behavioral parity
//!   only — pooling never affects output bytes).
//! - Go's `PreOrder()` returns a goroutine-backed channel. Rust exposes the same
//!   traversal eagerly via [`Node::pre_order`] returning a `Vec`, plus the
//!   zero-allocation callback variants [`Node::visit_pre_order`] /
//!   [`Node::visit_post_order`] which mirror the Go callbacks exactly.
//! - The query DSL (`map`/`filter`/`reduce`/field-access pipelines) is ported in
//!   the [`dsl`] module. The Go parser was generated by `pointlander/peg` from
//!   `dsl_parser.peg`; per the rewrite rules we do NOT hand-translate the
//!   generated artifact — instead [`dsl::parse`] is a hand-written
//!   recursive-descent parser implementing the same PEG grammar.

