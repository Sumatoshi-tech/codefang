func TestIsExcludedWithContent_GeneratedFile(t *testing.T) {
	t.Parallel()

	f := New()

	tests := []struct {
		name     string
		content  string
		excluded bool
	}{
		{"Code generated header", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n", true},
		{"DO NOT EDIT header", "// DO NOT EDIT. Auto-generated.\npackage api\n", true},
		{"AUTO-GENERATED header", "// AUTO-GENERATED FILE\npackage api\n", true},
		{"auto-generated header", "// auto-generated by tool\npackage api\n", true},
		{"Autogenerated header", "/* Autogenerated */\npackage api\n", true},
		{"@generated annotation", "// @generated\npackage api\n", true},
		{"Normal code", "package api\n\ntype Foo struct{}\n", false},
	}

	for _, tc := range tests {
		assert.Equal(t, tc.excluded, f.IsExcludedWithContent("pkg/api/types.go", []byte(tc.content)), tc.name)
	}
}

