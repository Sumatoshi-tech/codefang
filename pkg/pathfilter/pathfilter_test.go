func TestIsGeneratedPath(t *testing.T) {
	t.Parallel()

	f := New()

	// Generated suffixes should match.
	assert.True(t, f.IsGeneratedPath("api/types.pb.go"))
	assert.True(t, f.IsGeneratedPath("static/app.min.js"))

	// Generated filename prefixes should match.
	assert.True(t, f.IsGeneratedPath("pkg/zz_generated_deepcopy.go"))
	assert.True(t, f.IsGeneratedPath("pkg/mock_service.go"))

	// Vendor paths should NOT match (IsGeneratedPath skips enry.IsVendor).
	assert.False(t, f.IsGeneratedPath("vendor/github.com/foo/bar.go"))
	assert.False(t, f.IsGeneratedPath("node_modules/lodash/index.js"))

	// Normal source files should NOT match.
	assert.False(t, f.IsGeneratedPath("main.go"))
	assert.False(t, f.IsGeneratedPath("internal/server/handler.go"))
}

func TestIsGeneratedContent(t *testing.T) {
	t.Parallel()

	f := New()

	assert.True(t, f.IsGeneratedContent([]byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n")))
	assert.True(t, f.IsGeneratedContent([]byte("// @generated\npackage api\n")))
	assert.True(t, f.IsGeneratedContent([]byte("// AUTO-GENERATED FILE\npackage api\n")))

	// Normal code should NOT match.
	assert.False(t, f.IsGeneratedContent([]byte("package api\n\ntype Foo struct{}\n")))

	// Nil/empty content should NOT match.
	assert.False(t, f.IsGeneratedContent(nil))
	assert.False(t, f.IsGeneratedContent([]byte{}))
}

