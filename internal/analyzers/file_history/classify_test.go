func TestClassify_DotFile(t *testing.T) {
	t.Parallel()

	c := NewClassifier()

	// .editorconfig is not vendor per enry, so it's a dotfile.
	assert.Equal(t, CategoryDotFile, c.Classify(".editorconfig", nil))
	assert.Equal(t, CategoryDotFile, c.Classify(".bashrc", nil))
	// .gitignore is classified as vendor by enry.IsVendor.
	assert.Equal(t, CategoryVendor, c.Classify(".gitignore", nil))
}

func TestClassify_Binary(t *testing.T) {
	t.Parallel()

	c := NewClassifier()

	// Binary content (contains null bytes).
	binaryContent := []byte("hello\x00world")
	assert.Equal(t, CategoryBinary, c.Classify("data.bin", binaryContent))

	// Binary takes priority over other categories.
	assert.Equal(t, CategoryBinary, c.Classify("main.go", binaryContent))
}

func TestClassify_PriorityOrder(t *testing.T) {
	t.Parallel()

	c := NewClassifier()

	// Vendor takes priority over documentation (e.g., vendor/docs/readme.md).
	assert.Equal(t, CategoryVendor, c.Classify("vendor/docs/readme.md", nil))

	// Image takes priority over vendor.
	assert.Equal(t, CategoryImage, c.Classify("vendor/foo/logo.png", nil))
}

func TestAllCategories_ContainsAll(t *testing.T) {
	t.Parallel()

	expected := map[Category]bool{
		CategorySource:        true,
		CategoryVendor:        true,
		CategoryGenerated:     true,
		CategoryDocumentation: true,
		CategoryConfiguration: true,
		CategoryImage:         true,
		CategoryDotFile:       true,
		CategoryBinary:        true,
	}

	for _, cat := range AllCategories {
		assert.True(t, expected[cat], "unexpected category in AllCategories: %s", cat)
	}

	assert.Len(t, AllCategories, len(expected), "AllCategories length mismatch")
}
