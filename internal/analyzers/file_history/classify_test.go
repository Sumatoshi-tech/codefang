package filehistory

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestClassify_Source(t *testing.T) {
	t.Parallel()

	c := NewClassifier()

	assert.Equal(t, CategorySource, c.Classify("main.go", nil))
	assert.Equal(t, CategorySource, c.Classify("internal/server/handler.go", nil))
	assert.Equal(t, CategorySource, c.Classify("src/index.ts", nil))
	assert.Equal(t, CategorySource, c.Classify("lib/utils.py", nil))
	assert.Equal(t, CategorySource, c.Classify("Makefile", nil))
}

func TestClassify_Vendor(t *testing.T) {
	t.Parallel()

	c := NewClassifier()

	assert.Equal(t, CategoryVendor, c.Classify("vendor/github.com/foo/bar.go", nil))
	assert.Equal(t, CategoryVendor, c.Classify("node_modules/lodash/index.js", nil))
	assert.Equal(t, CategoryVendor, c.Classify("bower_components/jquery/jquery.js", nil))
	// enry.IsVendor matches minified files and .gitignore.
	assert.Equal(t, CategoryVendor, c.Classify("static/app.min.js", nil))
	assert.Equal(t, CategoryVendor, c.Classify("style.min.css", nil))
}

func TestClassify_Generated(t *testing.T) {
	t.Parallel()

	c := NewClassifier()

	// Path-based generated detection (suffix and prefix rules).
	assert.Equal(t, CategoryGenerated, c.Classify("api/types.pb.go", nil))
	assert.Equal(t, CategoryGenerated, c.Classify("pkg/zz_generated_deepcopy.go", nil))
	assert.Equal(t, CategoryGenerated, c.Classify("pkg/mock_service.go", nil))
	assert.Equal(t, CategoryGenerated, c.Classify("internal/wire_gen.go", nil))

	// Content-based generated detection.
	assert.Equal(t, CategoryGenerated, c.Classify("pkg/types.go",
		[]byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n")))
	assert.Equal(t, CategoryGenerated, c.Classify("pkg/types.go",
		[]byte("// @generated\npackage api\n")))
}

